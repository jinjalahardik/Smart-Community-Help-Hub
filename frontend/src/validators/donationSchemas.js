import { z } from 'zod';

const baseDonation = {
  category: z.string().min(1, 'Category is required'),
  title: z.string().min(3, 'Title must be at least 3 characters'),
  description: z.string().min(10, 'Description must be at least 10 characters'),
  quantity: z.coerce.number().positive('Quantity must be greater than 0'),
  unit: z.string().min(1, 'Unit is required'),
  pickupAddress: z.string().min(5, 'Pickup address is required'),
  city: z.string().min(1, 'City is required'),
  pinCode: z.string().regex(/^\d{6}$/, 'Enter a valid 6-digit PIN code'),
  preferredPickupDate: z.string().min(1, 'Preferred pickup date is required'),
  contactNumber: z.string().regex(/^[6-9]\d{9}$/, 'Enter a valid 10-digit mobile number'),
  availability: z.string().optional(),
  notes: z.string().optional(),
};

export const donationSchema = z.object({
  ...baseDonation,
  foodType: z.string().optional(),
  vegNonVeg: z.string().optional(),
  peopleServed: z.coerce.number().optional(),
  packaging: z.string().optional(),
  clothingType: z.string().optional(),
  genderCategory: z.string().optional(),
  ageGroup: z.string().optional(),
  size: z.string().optional(),
  condition: z.string().optional(),
  season: z.string().optional(),
  medicineName: z.string().optional(),
  batchNumber: z.string().optional(),
  manufacturer: z.string().optional(),
  expiryDate: z.string().optional(),
  prescriptionRequired: z.boolean().optional(),
  sealedCondition: z.boolean().optional(),
  bloodGroup: z.string().optional(),
  unitsAvailable: z.coerce.number().optional(),
  donationDate: z.string().optional(),
  lastDonationDate: z.string().optional(),
  medicalEligibility: z.boolean().optional(),
  preferredHospital: z.string().optional(),
});

export const emergencyRequestSchema = z.object({
  category: z.string().min(1, 'Category is required'),
  urgency: z.string().min(1, 'Urgency level is required'),
  title: z.string().min(3, 'Title must be at least 3 characters'),
  description: z.string().min(10, 'Description must be at least 10 characters'),
  requiredQuantity: z.coerce.number().positive('Required quantity must be greater than 0'),
  unit: z.string().min(1, 'Unit is required'),
  address: z.string().min(5, 'Address is required'),
  city: z.string().min(1, 'City is required'),
  pinCode: z.string().regex(/^\d{6}$/, 'Enter a valid 6-digit PIN code'),
  contactNumber: z.string().regex(/^[6-9]\d{9}$/, 'Enter a valid 10-digit mobile number'),
  affectedPeople: z.coerce.number().positive('Number of affected people is required'),
  vulnerablePersonInfo: z.string().optional(),
  neededBefore: z.string().min(1, 'Please specify when this is needed by'),
  consentGiven: z.boolean().refine((v) => v === true, 'Consent is required to submit this request'),
});
